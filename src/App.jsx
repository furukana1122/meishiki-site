const mod = (n, m) => ((n % m) + m) % m;

function getSetsuTime(y, m) {
  const key = String(y);
  if (SETSU_DATA[key]) return new Date(SETSU_DATA[key][m - 1]);
  const fixedDays = [6,4,6,5,6,6,7,8,8,8,8,7];
  return new Date(y, m - 1, fixedDays[m - 1], 12, 0);
}

function getTuhen(nikkan, targetKan) {
  if (!nikkan || !targetKan) return "";
  const isYang = ["甲","丙","戊","庚","壬"].includes(nikkan);
  const idx = isYang
    ? ["甲","丙","戊","庚","壬"].indexOf(nikkan)
    : ["乙","丁","己","辛","癸"].indexOf(nikkan);
  for (const [name, data] of Object.entries(TS_MAP)) {
    if ((isYang ? data.yang : data.yin)[idx] === targetKan) return name;
  }
  return "";
}

function calculate(year, month, day, hour, minute, gender) {
  const y = parseInt(year)||1990, m = parseInt(month)||1, d = parseInt(day)||1;
  const h = parseInt(hour)||0, mi = parseInt(minute)||0;
  const inputDate = new Date(y, m-1, d, h, mi);
  const inputTime = inputDate.getTime();

  const currentSetsuDate = getSetsuTime(y, m);
  const birthDayOnly = new Date(y, m-1, d).getTime();
  const currentSetsuOnly = new Date(currentSetsuDate.getFullYear(), currentSetsuDate.getMonth(), currentSetsuDate.getDate()).getTime();

  let targetSetsuDate = (inputTime >= currentSetsuDate.getTime())
    ? currentSetsuDate
    : getSetsuTime(m === 1 ? y-1 : y, m === 1 ? 12 : m-1);

  const baseDateOnly = new Date(targetSetsuDate.getFullYear(), targetSetsuDate.getMonth(), targetSetsuDate.getDate()).getTime();
  const zokanSu = Math.floor((birthDayOnly - baseDateOnly) / 86400000) + 1;

  const risshunTime = getSetsuTime(y, 2).getTime();
  let calcY = inputTime < risshunTime ? y-1 : y;
  const yKanIdx = mod(calcY-4, 10), yShiIdx = mod(calcY-4, 12);
  let mShiIdx = (inputTime >= currentSetsuDate.getTime())
    ? MONTH_SHI_IDX[mod(m-1, 12)]
    : MONTH_SHI_IDX[mod(m-2, 12)];
  const mKanIdx = mod(mod(mod(yKanIdx, 5)*2+2, 10) + mShiIdx-2, 10);
  const diffFromBase = Math.round((new Date(y, m-1, d).getTime() - new Date(1900,0,31).getTime()) / 86400000);
  const dKanIdx = mod(diffFromBase, 10), dShiIdx = mod(4+diffFromBase, 12);
  const nikkan = KAN[dKanIdx];

  // 天中殺
  const kuboIdx = mod(dShiIdx - dKanIdx, 12);
  const kubo = [SHI[mod(kuboIdx+10, 12)], SHI[mod(kuboIdx+11, 12)]];

  // 節入り日かどうか（時間が命式に影響するか）
  const birthOnSetsuDay = new Date(y, m-1, d).getTime() === currentSetsuOnly;

  const getZokan = (shi) => {
    const def = ZOKAN_TABLE[shi];
    if (!def) return "";
    if (zokanSu <= def.syoki[1]) return def.syoki[0];
    if (def.tyuki?.[0] && zokanSu <= (def.syoki[1] + def.tyuki[1])) return def.tyuki[0];
    return def.honki;
  };

  const pillars = [
    { label:"年柱", kan:KAN[yKanIdx], shi:SHI[yShiIdx] },
    { label:"月柱", kan:KAN[mKanIdx], shi:SHI[mShiIdx] },
    { label:"日柱", kan:KAN[dKanIdx], shi:SHI[dShiIdx] },
  ].map((p, i) => {
    const z = getZokan(p.shi);
    const un = JUUNI_UN_TABLE[nikkan]?.[p.shi] || "";
    return {
      ...p,
      zokan: z,
      tuhen: i === 2 ? "" : getTuhen(nikkan, p.kan),
      zokanTuhen: getTuhen(nikkan, z),
      juuniUn: un,
      energy: ENERGY_MAP[un] || 0
    };
  });

  const totalEnergy = pillars.reduce((s, p) => s+p.energy, 0);
  return { pillars, kubo, nikkan, totalEnergy, birthOnSetsuDay };
}

